const assert=require('node:assert/strict');
const M=require('../crosstab-models.js');
const spec={name:'功能',functional:'f',dysfunctional:'d',scale:'standard'};
const expected=['QAAAO','RIIIM','RIIIM','RIIIM','RRRRQ'];
for(let f=1;f<=5;f++)for(let d=1;d<=5;d++)assert.equal(M.calculateKano([{f,d}],spec).counts[expected[f-1][d-1]],1);
const r=M.calculateKano([{f:1,d:2},{f:1,d:5},{f:2,d:5},{f:3,d:3},{f:5,d:1},{f:1,d:1},{f:'',d:2},{f:10,d:2}],spec);
assert.equal(r.validN,6);assert.equal(r.effectiveN,4);assert.equal(r.excludedN,2);assert.equal(r.better,.5);assert.equal(r.worse,-.5);assert.match(r.classification,/并列/);
assert.equal(M.calculateKano([{f:5,d:1}],spec).better,null);
assert.equal(M.calculateKano([{f:5,d:4}],{...spec,scale:'reverse'}).counts.A,1);
assert.equal(M.calculateKano([{f:'①我很喜欢',d:'⑤我不喜欢'}],{...spec,scale:'labels'}).counts.O,1);
assert.equal(M.calculateKano([{f:1,d:2}],{...spec,scale:'labels'}).validN,0);
const psm={name:'PSM',tooCheap:'tc',cheap:'c',expensive:'e',tooExpensive:'te',validation:'ordered'};
const data=[{tc:10,c:20,e:30,te:40},{tc:20,c:30,e:40,te:50},{tc:'',c:20,e:30,te:40},{tc:50,c:20,e:30,te:40}];
const p=M.calculatePsm(data,psm);
assert.equal(p.validN,2);assert.equal(p.missingN,1);assert.equal(p.inconsistentN,1);assert.equal(p.excludedN,2);
assert.deepEqual(p.curve.find(x=>x.price===20),{price:20,tooCheap:.5,cheap:1,expensive:0,tooExpensive:0});
assert.deepEqual(p.curve.find(x=>x.price===30),{price:30,tooCheap:0,cheap:.5,expensive:.5,tooExpensive:0});
for(let i=1;i<p.curve.length;i++)for(const [j,k] of M.priceKeys.entries())assert.ok(j<2?p.curve[i][k]<=p.curve[i-1][k]:p.curve[i][k]>=p.curve[i-1][k]);
assert.ok(M.calculatePsm([],psm,[10,20]).curve.every(p=>p.cheap===null));
assert.equal(M.calculatePsm(data,{...psm,validation:'complete'}).validN,3);
assert.equal(M.calculatePsm([{tc:10,c:10,e:10,te:10}],psm).validN,1);
for(const v of ['',0,-1,'500-1000元','不知道',Infinity])assert.equal(M.parsePrice(v),null);
assert.equal(M.parsePrice('￥1,200.50元'),1200.5);
