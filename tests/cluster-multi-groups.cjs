const assert = require('node:assert/strict');
require('../cluster-core.js');
const core = globalThis.ClusterCore;
const headers = ['DV3_1','DV3_2','DV3_3','DV3_4','DV3_5'];
const rows = [{DV3_1:6.2636,DV3_2:2.0282,DV3_3:4.0564,DV3_4:.8375,DV3_5:15.6245},Object.fromEntries(headers.map(h=>[h,null]))];
assert.deepEqual(core.detectMultiSelectGroups(headers,rows),[]);
assert.ok(core.detectVariableTypes(rows,headers).every(d=>d.measurement==='scale' && !d.multiGroup && d.missingCount===1));
assert.deepEqual(core.detectMultiSelectGroups(['Q1_1','Q1_2']),[]);
assert.deepEqual(core.detectMultiSelectGroups(['Q1_1','Q1_2'],[{Q1_1:1,Q1_2:2},{Q1_1:0,Q1_2:5}]),[]);
const binaryHeaders=['A7_1 冰箱','A7_2 空调'];
const binaryRows=[{'A7_1 冰箱':'1','A7_2 空调':'0'},{'A7_1 冰箱':null,'A7_2 空调':'1'}];
assert.equal(core.detectMultiSelectGroups(binaryHeaders,binaryRows)[0].name,'A7');
assert.equal(core.detectVariableTypes(binaryRows,binaryHeaders)[0].missingCount,1);
assert.equal(binaryRows[1]['A7_1 冰箱'],null);
const lateRows=Array.from({length:1000},()=>({Q1_1:1,Q1_2:0}));lateRows.push({Q1_1:.123,Q1_2:1});
assert.deepEqual(core.detectMultiSelectGroups(['Q1_1','Q1_2'],lateRows),[]);
assert.deepEqual(core.detectMultiSelectGroups(['Q1_1','Q1_2'],[{Q1_1:1,Q1_2:null}]),[]);
assert.equal(core.detectMultiSelectGroups(['T2_R1','T2_R2'],[{T2_R1:'是',T2_R2:'否'}])[0].positiveValue,'是');
console.log('PASS multi-select detection: continuous, ratings, labelled binary, missing and full-row validation');
