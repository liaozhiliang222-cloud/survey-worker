import assert from "node:assert/strict";
import fs from "node:fs";
import { selectPptTemplate, setPptPageLayout } from "../lib/ppt-template-state.mjs";
import { normalizePptScript } from "../lib/ppt-script-workflow.mjs";

const blue = JSON.parse(fs.readFileSync(new URL("../pptx_report/templates/research-business-blue-v1/layout_catalog.json", import.meta.url)));
const old = JSON.parse(fs.readFileSync(new URL("../pptx_report/templates/qualitative-tech-blue-v2/layout_catalog.json", import.meta.url)));
const script = { schema_version: "surveykit.ppt_script.v1", style_profile: { id: old.template_id, version: old.version }, pages: [{ id: "page1", page_type: "recommendation", title: "规则透明能降低用户的决策负担", key_message: "用户希望事先知道规则", layout_variant: "action_roadmap", layout_binding: { locked: true }, evidence_ids: ["e1"], content_structure: [{ title: "先说明规则", body: "在用户提交前解释收费" }], quotes: [] }] };
const snapshot = structuredClone(script);
const chosen = selectPptTemplate(script, blue);
assert.deepEqual(script, snapshot, "selection never mutates the saved script");
assert.deepEqual(chosen.pages[0].content_structure, script.pages[0].content_structure);
assert.deepEqual(chosen.pages[0].evidence_ids, ["e1"]);
assert.equal(chosen.pages[0].layout_binding.locked, false, "a lock belongs to a template, not its unrelated replacement");
const manual = setPptPageLayout(chosen, "page1", "bb_roadmap", blue);
manual.pages[0].layout_binding.locked = true;
const back = selectPptTemplate(manual, old);
assert.equal(back.pages[0].layout_variant, "action_roadmap");
assert.equal(back.pages[0].layout_binding.locked, true);
const again = selectPptTemplate(back, blue);
assert.equal(again.pages[0].layout_variant, "bb_roadmap");
assert.equal(again.pages[0].layout_binding.locked, true);
assert.throws(() => setPptPageLayout(again, "page1", "bb_actions", blue), /解锁/);
assert.throws(() => setPptPageLayout(chosen, "page1", "bb_quotes", blue), /不适用/);
const normalized = normalizePptScript({ page: { title: "清晰的收费说明帮助用户作出选择", style_profile: { id: old.template_id } } }, { existingScript: again, targetPageId: "page1", evidence: [{ id: "e1", type: "qualitative", claim: "用户希望事先知道规则", value: {} }] });
assert.equal(normalized.style_profile.id, blue.template_id);
assert.equal(normalized.pages[0].layout_binding.locked, true);
assert.equal(normalized.pages[0].layout_binding.template_choices[old.template_id].variant, "action_roadmap");
console.log("business-blue-state-smoke: selection, round-trip locks, incompatibility, evidence preservation and page revision passed");
